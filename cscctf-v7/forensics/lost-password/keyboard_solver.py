#!/usr/bin/env python3
"""Decode USB HID keyboard reports from a PCAP into typed text."""
import subprocess

PCAP   = "capture_02.pcapng"
DEVICE = "1.3.1"

NORMAL = {
    0x04:'a',0x05:'b',0x06:'c',0x07:'d',0x08:'e',0x09:'f',0x0a:'g',0x0b:'h',
    0x0c:'i',0x0d:'j',0x0e:'k',0x0f:'l',0x10:'m',0x11:'n',0x12:'o',0x13:'p',
    0x14:'q',0x15:'r',0x16:'s',0x17:'t',0x18:'u',0x19:'v',0x1a:'w',0x1b:'x',
    0x1c:'y',0x1d:'z',
    0x1e:'1',0x1f:'2',0x20:'3',0x21:'4',0x22:'5',0x23:'6',0x24:'7',0x25:'8',
    0x26:'9',0x27:'0',
    0x28:'\n',0x29:'[ESC]',0x2a:'[BKSP]',0x2b:'\t',0x2c:' ',
    0x2d:'-',0x2e:'=',0x2f:'[',0x30:']',0x31:'\\',0x33:';',0x34:"'",
    0x36:',',0x37:'.',0x38:'/',
}
SHIFT = {
    0x04:'A',0x05:'B',0x06:'C',0x07:'D',0x08:'E',0x09:'F',0x0a:'G',0x0b:'H',
    0x0c:'I',0x0d:'J',0x0e:'K',0x0f:'L',0x10:'M',0x11:'N',0x12:'O',0x13:'P',
    0x14:'Q',0x15:'R',0x16:'S',0x17:'T',0x18:'U',0x19:'V',0x1a:'W',0x1b:'X',
    0x1c:'Y',0x1d:'Z',
    0x1e:'!',0x1f:'@',0x20:'#',0x21:'$',0x22:'%',0x23:'^',0x24:'&',0x25:'*',
    0x26:'(',0x27:')',
    0x2c:' ',0x2d:'_',0x2e:'+',0x2f:'{',0x30:'}',0x31:'|',0x33:':',0x34:'"',
    0x36:'<',0x37:'>',0x38:'?',
}

rows = subprocess.check_output(
    ["tshark","-r",PCAP,"-Y",f'usb.src == "{DEVICE}" && usbhid.data',
     "-T","fields","-e","usbhid.data"], text=True
).strip().splitlines()

prev_keys = set()
output = ""
for line in rows:
    if len(line) < 16: continue
    b = bytes.fromhex(line.replace(":",""))
    if len(b) < 8: continue
    shift_held = bool(b[0] & 0x22)
    keys = set(b[2:8]) - {0}
    for k in sorted(keys - prev_keys):
        m = SHIFT if shift_held else NORMAL
        output += m.get(k, f"[{k:02x}]")
    prev_keys = keys

print(output)
